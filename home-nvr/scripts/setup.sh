#!/usr/bin/env bash
# First-time setup on the mini PC (Debian or Ubuntu). Safe to re-run.
set -euo pipefail
cd "$(dirname "$0")/.."

if ! command -v docker >/dev/null 2>&1; then
  echo "Docker is not installed. Install Docker Engine first:"
  echo "  curl -fsSL https://get.docker.com | sudo sh"
  echo "  sudo usermod -aG docker \$USER   (then log out and back in)"
  exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
  echo "The Docker Compose plugin is missing: sudo apt install docker-compose-plugin"
  exit 1
fi

if [ ! -f .env ]; then
  cp .env.example .env
  chmod 600 .env
  tz="$(cat /etc/timezone 2>/dev/null || timedatectl show -p Timezone --value 2>/dev/null || true)"
  if [ -n "$tz" ]; then
    sed -i "s|^TZ=.*|TZ=$tz|" .env
  fi
  echo "Created .env (timezone: ${tz:-Etc/UTC}). Set the camera login in it before adding cameras."
fi

storage="$(grep -E '^STORAGE_PATH=' .env | cut -d= -f2-)"
storage="${storage:-./storage}"
mkdir -p "$storage"
echo "Recordings go to: $storage ($(df -h --output=avail "$storage" | tail -1 | tr -d ' ') free)"

# Pass the GPU through for video decoding and Intel GPU detection when there is one.
render="$(ls /dev/dri/renderD* 2>/dev/null | head -1 || true)"
if [ -n "$render" ]; then
  cat > docker-compose.override.yml <<YAML
# Generated by scripts/setup.sh for this machine's GPU.
services:
  frigate:
    devices:
      - $render:/dev/dri/renderD128
    group_add:
      - "$(stat -c %g "$render")"
YAML
  echo "GPU found at $render: hardware video decoding enabled."
  if grep -qi 'GenuineIntel' /proc/cpuinfo; then
    echo "Intel CPU: uncomment the detectors/model block in config/config.yml to run detection on the GPU."
  fi
else
  rm -f docker-compose.override.yml
  echo "No GPU render device found: decoding and detection will run on the CPU."
fi

docker compose pull
docker compose up -d

echo "Waiting for Frigate to start..."
for _ in $(seq 1 90); do
  if curl -sk -o /dev/null --max-time 2 https://127.0.0.1:8971/; then break; fi
  sleep 2
done

ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
echo
echo "Frigate is running: https://${ip:-<this-pc-ip>}:8971  (accept the certificate warning on the LAN)"
if docker logs frigate 2>&1 | grep -q 'Password:'; then
  echo "First-run admin login (user: admin):"
  docker logs frigate 2>&1 | grep 'Password:' | tail -1
else
  echo "Log in with your existing admin account. (The generated password is only"
  echo "printed on the very first start; to reset it set auth.reset_admin_password.)"
fi
echo
echo "Next: change the admin password (Settings > Users), add cameras, then run"
echo "  ./scripts/remote-access.sh   for phone access away from home."
